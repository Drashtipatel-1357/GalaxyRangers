<h2>Impact</h2>
<p class="fs-4 mb-0" style="text-align: justify;">
    The flood destroyed 25 homes and displaced 135 people. It also damaged a school, health post, bridge, trekking trails, and a hydropower plant.
    Although the event occurred during daylight and unfolded in phases, which helped prevent loss of life, the damage was extensive. The flood carried debris as far as 80 km downstream and reshaped parts of the river valley.
</p>

<h2>Why glaciers matter</h2>
<p class="fs-4" style="text-align: justify;">
Glaciers store freshwater and slowly release it into rivers that support communities, agriculture, hydropower, and ecosystems. But as temperatures rise, glaciers can shrink, and glacial lakes can expand, increasing the risk of sudden outburst floods.
The Hindu Kush Himalaya region is warming rapidly, and it now contains more than 25,000 glacial lakes. The Thame event shows that even smaller lakes can become dangerous when they grow quickly or sit above vulnerable communities.
</p>

<h2>How SAR can help</h2>
<p class="fs-4" style="text-align: justify;">
SAR (Synthetic Aperture Radar) is a satellite technology that uses radar signals rather than visible light. Because radar can penetrate clouds and work in darkness, it is especially useful for monitoring remote, mountainous regions such as the Himalayas.
By comparing SAR images taken on different dates, researchers can track changes in glacial lakes, shorelines, and surrounding terrain. This information can support earlier risk assessment, better planning, and stronger early-warning systems for communities living downstream.
</p>

