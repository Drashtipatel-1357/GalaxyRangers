                    <p class="fs-4" style="text-align: justify;">
                        On 16 August 2024, Thame village in Nepal’s Everest region was struck by a sudden glacial lake outburst flood (GLOF). In less than half an hour, water, sediment, and debris swept through the valley, damaging homes, a school, a health post, a bridge, and local infrastructure.
Thame is a high-altitude village in the Khumbu region, near the route to Mount Everest. Its people depend on tourism, agriculture, and mountain infrastructure, making the flood’s impact especially severe for the local community.
<br>
The flood began in the headwaters of the Thame Valley, where two relatively small glacial lakes—the Upper and Lower Ngole lakes—were located. A rock avalanche or glacier-calving event likely disturbed the upper lake, creating a powerful wave that overtopped its moraine dam.
This triggered a cascading GLOF: the upper lake’s outburst flowed into the lower lake, causing its moraine dam to fail as well. Together, the two lakes released approximately 770,000 cubic metres of water—enough to fill about 185 Olympic-sized swimming pools.
The flood wave reached Thame village within about 22 minutes, with an initial peak discharge estimated at more than 800 cubic metres per second.
